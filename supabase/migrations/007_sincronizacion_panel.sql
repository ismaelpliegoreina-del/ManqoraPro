-- 007 · Soporte para conectar el panel: id numérico de la app, copia completa del objeto (data), fecha de cambio
create function public.touch_updated() returns trigger
language plpgsql set search_path = '' as $$
begin new.updated_at := now(); return new; end $$;

do $$
declare t text;
begin
  foreach t in array array['employees','services','upsells','clients','appointments','sales','products',
                           'expenses','cash_closures','waitlist','time_blocks']
  loop
    execute format('alter table public.%I add column app_id bigint generated by default as identity', t);
    execute format('alter table public.%I add column data jsonb not null default %L::jsonb', t, '{}');
    execute format('alter table public.%I add column updated_at timestamptz not null default now()', t);
    execute format('create unique index %I on public.%I (tenant_id, app_id)', t || '_app_uq', t);
    execute format('create index %I on public.%I (tenant_id, updated_at)', t || '_upd_idx', t);
    execute format('create trigger %I before update on public.%I for each row execute function public.touch_updated()', t || '_touch', t);
  end loop;
end $$;

-- Otros datos pequeños del negocio (pases VIP, archivo de clientes anonimizados, etc.)
create table public.tenant_docs (
  tenant_id uuid not null references public.tenants(id) on delete cascade,
  key text not null check (key in ('passes','clientsArchive','productsArchive','inventory','notices')),
  data jsonb not null default '[]'::jsonb,
  updated_at timestamptz not null default now(),
  primary key (tenant_id, key)
);
alter table public.tenant_docs enable row level security;
revoke all on public.tenant_docs from anon, authenticated;
grant select, insert, update on public.tenant_docs to authenticated;
create policy tenant_docs_sel on public.tenant_docs for select to authenticated using (public.is_member(tenant_id));
create policy tenant_docs_ins on public.tenant_docs for insert to authenticated
  with check (public.role_in(tenant_id) is not null and public.tenant_writable(tenant_id));
create policy tenant_docs_upd on public.tenant_docs for update to authenticated
  using (public.role_in(tenant_id) is not null and public.tenant_writable(tenant_id))
  with check (public.role_in(tenant_id) is not null and public.tenant_writable(tenant_id));
create trigger tenant_docs_touch before update on public.tenant_docs for each row execute function public.touch_updated();

-- El stock lo mueven los cobros, así que cualquier miembro puede actualizar productos
drop policy products_upd on public.products;
create policy products_upd on public.products for update to authenticated
  using (public.role_in(tenant_id) is not null and public.tenant_writable(tenant_id))
  with check (public.role_in(tenant_id) is not null and public.tenant_writable(tenant_id));

-- Ventas: importes e identificadores inmutables; solo se puede actualizar la copia de datos (marca de anulada, comisión)
grant update (data, updated_at) on public.sales to authenticated;
create policy sales_upd on public.sales for update to authenticated
  using (public.role_in(tenant_id) is not null and public.tenant_writable(tenant_id))
  with check (public.role_in(tenant_id) is not null and public.tenant_writable(tenant_id));

-- El panel puede encolar correos, solo a emails de clientes del propio negocio
grant insert on public.outbox_emails to authenticated;
create policy outbox_ins on public.outbox_emails for insert to authenticated
  with check (
    public.role_in(tenant_id) is not null and public.tenant_writable(tenant_id)
    and template in ('confirm','pending','cancel','change','reminder')
    and exists (select 1 from public.clients c where c.tenant_id = outbox_emails.tenant_id and c.email = lower(outbox_emails.to_email)));

-- Recibos: se respeta el número que traiga la app; si no trae, se asigna el siguiente
create or replace function public.sales_before_insert() returns trigger
language plpgsql security definer set search_path = '' as $$
declare m text[];
begin
  if new.receipt_no is null or new.receipt_no = '' then
    new.receipt_no := public.next_receipt_no(new.tenant_id, new.sold_at);
  else
    m := regexp_match(new.receipt_no, '^R-(\d{4})-(\d+)$');
    if m is not null then
      insert into public.receipt_counters(tenant_id, year, last) values (new.tenant_id, m[1]::int, m[2]::int)
      on conflict (tenant_id, year) do update set last = greatest(public.receipt_counters.last, excluded.last);
    end if;
  end if;
  new.created_by := coalesce(new.created_by, (select auth.uid()));
  return new;
end $$;
revoke all on function public.sales_before_insert() from public, anon, authenticated;
